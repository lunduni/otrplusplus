@dataclass
class _RatchetParty:
    root_key: bytes
    sending_chain_key: Optional[bytes]
    receiving_chain_key: Optional[bytes]
    dh_self: X25519PrivateKey
    dh_remote: Any
    send_counter: int
    recv_counter: int


def _ratchet_auth_bytes(counter: int, ephemeral_pub: str, ciphertext: str) -> bytes:
    return json_dumps_canonical(
        {
            "counter": int(counter),
            "ephemeral_pub": ephemeral_pub,
            "ciphertext": ciphertext,
        }
    )


class X3DHRatchetBaselineAdapter(ProtocolAdapter):
    """Protocol-level baseline: X3DH-style setup + DH/symmetric ratchet + EtM HMAC.

    This intentionally excludes adaptive deniability disclosure logic and signature mode
    switching, making it a better apples-to-apples baseline than micro crypto tests.
    """

    name = "x3dh_ratchet_baseline"

    def __init__(self, *, dh_rotate_interval: int = 5) -> None:
        self.dh_rotate_interval = int(dh_rotate_interval)
        self.alice: _RatchetParty | None = None
        self.bob: _RatchetParty | None = None

    def setup(self) -> None:
        a_ek = X25519PrivateKey.generate()
        b_ik = X25519PrivateKey.generate()
        b_spk = X25519PrivateKey.generate()
        b_opk = X25519PrivateKey.generate()

        dh1 = a_ek.exchange(b_ik.public_key())
        dh2 = a_ek.exchange(b_spk.public_key())
        dh3 = a_ek.exchange(b_opk.public_key())
        root0 = hkdf_sha256(
            dh1 + dh2 + dh3, salt=None, info=b"OTR++-AD/x3dh", length=32
        )

        a_root, a_send_ck = kdf_root(root0, a_ek.exchange(b_spk.public_key()))
        b_root, b_recv_ck = kdf_root(root0, b_spk.exchange(a_ek.public_key()))

        self.alice = _RatchetParty(
            root_key=a_root,
            sending_chain_key=a_send_ck,
            receiving_chain_key=None,
            dh_self=a_ek,
            dh_remote=b_spk.public_key(),
            send_counter=0,
            recv_counter=0,
        )
        self.bob = _RatchetParty(
            root_key=b_root,
            sending_chain_key=None,
            receiving_chain_key=b_recv_ck,
            dh_self=b_spk,
            dh_remote=a_ek.public_key(),
            send_counter=0,
            recv_counter=0,
        )

    def _maybe_rotate_send(self, party: _RatchetParty) -> None:
        if party.sending_chain_key is None:
            raise ValueError("missing sending chain")
        if self.dh_rotate_interval <= 0:
            return
        if party.send_counter > 0 and party.send_counter % self.dh_rotate_interval == 0:
            party.dh_self = X25519PrivateKey.generate()
            dh_secret = party.dh_self.exchange(party.dh_remote)
            party.root_key, party.sending_chain_key = kdf_root(
                party.root_key, dh_secret
            )
            party.send_counter = 0

    def _ratchet_receive(self, party: _RatchetParty, new_remote_pub: Any) -> None:
        party.dh_remote = new_remote_pub
        dh_secret = party.dh_self.exchange(new_remote_pub)
        party.root_key, party.receiving_chain_key = kdf_root(party.root_key, dh_secret)
        party.recv_counter = 0

    def send(self, plaintext: str) -> Dict[str, Any]:
        assert self.alice is not None
        a = self.alice
        self._maybe_rotate_send(a)

        if a.sending_chain_key is None:
            raise ValueError("alice missing sending chain")

        msg_key, next_ck = kdf_chain(a.sending_chain_key)
        enc_key = hkdf_sha256(msg_key, salt=None, info=b"OTR++-AD/msg_enc", length=32)
        mac_key = hkdf_sha256(msg_key, salt=None, info=b"OTR++-AD/msg_mac", length=32)
        nonce = hkdf_sha256(msg_key, salt=None, info=b"OTR++-AD/msg_nonce", length=12)

        eph_b64 = b64e(x25519_public_bytes(a.dh_self.public_key()))
        counter = a.send_counter
        aad = json_dumps_canonical({"counter": counter, "ephemeral_pub": eph_b64})
        ct = encrypt(enc_key, plaintext.encode("utf-8"), aad=aad, nonce=nonce)
        ct_b64 = b64e(ct)
        mac = b64e(hmac_sha256(mac_key, _ratchet_auth_bytes(counter, eph_b64, ct_b64)))

        a.sending_chain_key = next_ck
        a.send_counter += 1

        return {
            "counter": counter,
            "ephemeral_pub": eph_b64,
            "ciphertext": ct_b64,
            "mac": mac,
        }

    def receive(self, message: Dict[str, Any]) -> str:
        assert self.bob is not None
        b = self.bob
        if b.receiving_chain_key is None:
            raise ValueError("bob missing receiving chain")

        counter = int(message["counter"])
        remote_pub = x25519_public_from_bytes(b64d(str(message["ephemeral_pub"])))
        remote_b64 = b64e(x25519_public_bytes(remote_pub))
        current_b64 = b64e(x25519_public_bytes(b.dh_remote))
        if remote_b64 != current_b64:
            self._ratchet_receive(b, remote_pub)
            if b.receiving_chain_key is None:
                raise ValueError("bob missing receiving chain after ratchet")

        while b.recv_counter < counter:
            _, next_ck = kdf_chain(b.receiving_chain_key)
            b.receiving_chain_key = next_ck
            b.recv_counter += 1

        msg_key, next_ck = kdf_chain(b.receiving_chain_key)
        b.receiving_chain_key = next_ck
        b.recv_counter += 1

        enc_key = hkdf_sha256(msg_key, salt=None, info=b"OTR++-AD/msg_enc", length=32)
        mac_key = hkdf_sha256(msg_key, salt=None, info=b"OTR++-AD/msg_mac", length=32)
        aad = json_dumps_canonical(
            {"counter": counter, "ephemeral_pub": message["ephemeral_pub"]}
        )

        expected_mac = hmac_sha256(
            mac_key,
            _ratchet_auth_bytes(
                counter, message["ephemeral_pub"], message["ciphertext"]
            ),
        )
        if not hmac.compare_digest(expected_mac, b64d(message["mac"])):
            raise ValueError("invalid mac")

        pt = decrypt(enc_key, b64d(message["ciphertext"]), aad=aad)
        return pt.decode("utf-8")


@dataclass
class TrialMetrics:
    setup_ms: float
    first_send_ms: float
    first_recv_ms: float
    avg_send_ms: float
    avg_recv_ms: float
    avg_roundtrip_ms: float
    p95_roundtrip_ms: float


def _percentile(data: List[float], p: float) -> float:
    if not data:
        return 0.0
    if len(data) == 1:
        return data[0]
    k = int(round((len(data) - 1) * p))
    k = max(0, min(k, len(data) - 1))
    return sorted(data)[k]


def run_trial(
    adapter: ProtocolAdapter, *, messages: int, payload_bytes: int
) -> TrialMetrics:
    payload = "x" * payload_bytes

    _, setup_ms = _time_call(adapter.setup)

    msg, first_send_ms = _time_call(adapter.send, payload)
    _, first_recv_ms = _time_call(adapter.receive, msg)

    send_times: List[float] = []
    recv_times: List[float] = []
    rtt_times: List[float] = []

    for i in range(max(0, messages - 1)):
        text = f"{payload}:{i}"
        msg, send_ms = _time_call(adapter.send, text)
        _, recv_ms = _time_call(adapter.receive, msg)
        send_times.append(send_ms)
        recv_times.append(recv_ms)
        rtt_times.append(send_ms + recv_ms)

    return TrialMetrics(
        setup_ms=setup_ms,
        first_send_ms=first_send_ms,
        first_recv_ms=first_recv_ms,
        avg_send_ms=statistics.mean(send_times) if send_times else 0.0,
        avg_recv_ms=statistics.mean(recv_times) if recv_times else 0.0,
        avg_roundtrip_ms=statistics.mean(rtt_times) if rtt_times else 0.0,
        p95_roundtrip_ms=_percentile(rtt_times, 0.95) if rtt_times else 0.0,
    )


def summarize(
    protocol: str, trials: List[TrialMetrics], messages: int, payload_bytes: int
) -> Dict[str, Any]:
    return {
        "protocol": protocol,
        "messages": messages,
        "payload_bytes": payload_bytes,
        "trials": len(trials),
        "setup_ms_mean": statistics.mean(t.setup_ms for t in trials),
        "first_send_ms_mean": statistics.mean(t.first_send_ms for t in trials),
        "first_recv_ms_mean": statistics.mean(t.first_recv_ms for t in trials),
        "steady_send_ms_mean": statistics.mean(t.avg_send_ms for t in trials),
        "steady_recv_ms_mean": statistics.mean(t.avg_recv_ms for t in trials),
        "steady_rtt_ms_mean": statistics.mean(t.avg_roundtrip_ms for t in trials),
        "steady_rtt_ms_p95_mean": statistics.mean(t.p95_roundtrip_ms for t in trials),
    }


def _print_table(rows: List[Dict[str, Any]]) -> None:
    headers = [
        "protocol",
        "setup_ms_mean",
        "first_send_ms_mean",
        "first_recv_ms_mean",
        "steady_send_ms_mean",
        "steady_recv_ms_mean",
        "steady_rtt_ms_mean",
        "steady_rtt_ms_p95_mean",
    ]

    print("\nBenchmark Results (milliseconds)")
    print("-" * 110)
    print(" ".join(h.ljust(22) for h in headers))
    print("-" * 110)
    for row in rows:
        print(
            f"{row['protocol']:<22} "
            f"{row['setup_ms_mean']:<22.3f} "
            f"{row['first_send_ms_mean']:<22.3f} "
            f"{row['first_recv_ms_mean']:<22.3f} "
            f"{row['steady_send_ms_mean']:<22.3f} "
            f"{row['steady_recv_ms_mean']:<22.3f} "
            f"{row['steady_rtt_ms_mean']:<22.3f} "
            f"{row['steady_rtt_ms_p95_mean']:<22.3f}"
        )
    print("-" * 110)


def _write_csv(path: str, rows: List[Dict[str, Any]]) -> None:
    fields = list(rows[0].keys()) if rows else []
    with open(path, "w", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(f, fieldnames=fields)
        writer.writeheader()
        writer.writerows(rows)


def main(argv: List[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description="Benchmark OTR++ and comparison baselines."
    )
    parser.add_argument(
        "--messages",
        type=int,
        default=300,
        help="Messages per trial (including first message).",
    )
    parser.add_argument(
        "--payload-bytes",
        type=int,
        default=256,
        help="Plaintext payload size in bytes.",
    )
    parser.add_argument(
        "--repeats",
        type=int,
        default=5,
        help="Number of benchmark repeats per protocol.",
    )
    parser.add_argument(
        "--comparison-set",
        type=str,
        default="valid",
        choices=["valid", "micro", "all"],
        help="valid: protocol-level baseline, micro: crypto micro-baselines, all: both.",
    )
    parser.add_argument("--csv", type=str, default="", help="Optional output CSV path.")
    args = parser.parse_args(argv)

    if args.messages < 2:
        raise ValueError("--messages must be >= 2")
    if args.payload_bytes < 1:
        raise ValueError("--payload-bytes must be >= 1")
    if args.repeats < 1:
        raise ValueError("--repeats must be >= 1")

    host = "127.0.0.1"
    port = _pick_free_port()
    _, _ = start_prekey_server_in_thread(host=host, port=port)
    server_url = f"http://{host}:{port}"

    # Give the background server a brief startup moment.
    time.sleep(0.1)

    protocols: List[ProtocolAdapter] = [
        OTRPPAdapter(name="otrpp_deniable", mode=DENIABLE, server_url=server_url),
        OTRPPAdapter(name="otrpp_verifiable", mode=VERIFIABLE, server_url=server_url),
    ]
    if args.comparison_set in ("valid", "all"):
        protocols.append(X3DHRatchetBaselineAdapter())
    if args.comparison_set in ("micro", "all"):
        protocols.extend([ECDHAESGCMAdapter(), PSKAESGCMAdapter()])

    rows: List[Dict[str, Any]] = []
    for proto in protocols:
        trials: List[TrialMetrics] = []
        for _ in range(args.repeats):
            trials.append(
                run_trial(
                    proto, messages=args.messages, payload_bytes=args.payload_bytes
                )
            )
        rows.append(summarize(proto.name, trials, args.messages, args.payload_bytes))

    _print_table(rows)
    if args.csv:
        _write_csv(args.csv, rows)
        print(f"\nSaved CSV: {args.csv}")

    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
