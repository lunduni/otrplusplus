def _pick_free_port() -> int:
    with socket.socket(socket.AF_INET, socket.SOCK_STREAM) as s:
        s.bind(("127.0.0.1", 0))
        return int(s.getsockname()[1])


def _ms(start_ns: int, end_ns: int) -> float:
    return (end_ns - start_ns) / 1_000_000.0


def _time_call(func, *args, **kwargs):
    t0 = time.perf_counter_ns()
    out = func(*args, **kwargs)
    t1 = time.perf_counter_ns()
    return out, _ms(t0, t1)


class ProtocolAdapter:
    name: str = "adapter"

    def setup(self) -> None:
        raise NotImplementedError

    def send(self, plaintext: str) -> Dict[str, Any]:
        raise NotImplementedError

    def receive(self, message: Dict[str, Any]) -> str:
        raise NotImplementedError


class OTRPPAdapter(ProtocolAdapter):
    def __init__(self, *, name: str, mode: int, server_url: str) -> None:
        self.name = name
        self.mode = mode
        self.server_url = server_url
        self.alice: Client | None = None
        self.bob: Client | None = None
        self.bob_id: str | None = None

    def setup(self) -> None:
        # Use unique IDs per trial so each run starts clean.
        alice_id = f"alice-{uuid4().hex[:8]}"
        bob_id = f"bob-{uuid4().hex[:8]}"
        self.alice = Client(user_id=alice_id, server_url=self.server_url)
        self.bob = Client(user_id=bob_id, server_url=self.server_url)
        self.alice.publish_prekeys()
        self.bob.publish_prekeys()
        self.bob_id = bob_id

    def send(self, plaintext: str) -> Dict[str, Any]:
        assert self.alice is not None
        assert self.bob_id is not None
        with contextlib.redirect_stdout(io.StringIO()):
            return self.alice.send_message(
                peer_id=self.bob_id, text=plaintext, mode=self.mode
            )

    def receive(self, message: Dict[str, Any]) -> str:
        assert self.bob is not None
        with contextlib.redirect_stdout(io.StringIO()):
            return self.bob.receive_message(message)


class ECDHAESGCMAdapter(ProtocolAdapter):
    name = "ecdh_aesgcm_baseline"

    def __init__(self) -> None:
        self._aesgcm: AESGCM | None = None

    def setup(self) -> None:
        a_priv = X25519PrivateKey.generate()
        b_priv = X25519PrivateKey.generate()
        shared = a_priv.exchange(b_priv.public_key())
        key = HKDF(
            algorithm=hashes.SHA256(),
            length=32,
            salt=None,
            info=b"bench/ecdh-aesgcm",
        ).derive(shared)
        self._aesgcm = AESGCM(key)

    def send(self, plaintext: str) -> Dict[str, Any]:
        assert self._aesgcm is not None
        nonce = os.urandom(12)
        ct = self._aesgcm.encrypt(nonce, plaintext.encode("utf-8"), b"")
        return {"nonce": nonce, "ciphertext": ct}

    def receive(self, message: Dict[str, Any]) -> str:
        assert self._aesgcm is not None
        pt = self._aesgcm.decrypt(message["nonce"], message["ciphertext"], b"")
        return pt.decode("utf-8")


