"""Benchmark OTR++ against both protocol-level and micro baselines.

Run from repository root:
    python -m evaluation.benchmark_protocols --messages 300 --repeats 5

Notes:
- The OTR++ measurements are codebase-native (client/server/protocol modules).
- For fairer comparison, use `--comparison-set valid`, which compares against a
    protocol-level X3DH+ratchet baseline (without adaptive deniability).
- `--comparison-set micro` keeps very small crypto-only baselines for overhead intuition.


This benchmarking code was generated by AI pair programming with GPT-4, 
and is not intended for production use. It may contain bugs or inaccuracies, 
and should be reviewed carefully before use.

"""

